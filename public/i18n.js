// ---------- Engine ----------
const STORE = 'playroomLang';
let lang = 'en';
let dict = D.en;
let plural = new Intl.PluralRules('en');

export const getLang = () => lang;

/** Translated text. vars fills the {placeholders}; vars.n picks the plural form. */
export function t(key, vars = {}) {
  let v = dict[key] ?? D.en[key] ?? key;
  if (typeof v === 'object') v = v[plural.select(Number(vars.n) || 0)] ?? v.other;
  return String(v).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

function savedLang() {
  try {
    return localStorage.getItem(STORE);
  } catch {
    return null;
  }
}

/** Loads a language (lang/xx.js on demand) and remembers the choice in the browser */
export async function setLang(code, { save = true } = {}) {
  if (!LANGS.some(([c]) => c === code)) code = 'en';
  if (!D[code]) {
    try {
      D[code] = (await import(`./lang/${code}.js`)).default;
    } catch {
      code = 'en';
    }
  }
  lang = code;
  dict = D[code];
  plural = new Intl.PluralRules(code);
  document.documentElement.lang = code;
  document.documentElement.dir = RTL.includes(code) ? 'rtl' : 'ltr';
  if (save) {
    try {
      localStorage.setItem(STORE, code);
    } catch {}
  }
  return code;
}

/** Starting language: the last one chosen, otherwise English */
export const initLang = () => setLang(savedLang() || 'en', { save: false });
